package controlador;

/**
 * Animaciones de Cabito que el controlador le pide a la vista después de
 * ciertas acciones. La vista decide cómo se ven.
 */
public enum Animacion {

    /** Cabito acaba de jugar (se le ve corriendo un momento). */
    JUGAR,
    /** Cabito llegó a otro mundo (entra caminando). */
    VIAJAR
}
